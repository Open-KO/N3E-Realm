#pragma once
#include <GL/gl.h>
#include <cctype>
#include <string>
// Original small bitmap alphabet: no font/runtime asset dependency.
inline void hud_text(const std::string &text, int x, int y, int height,
                     float red = .9f, float green = .95f, float blue = 1) {
  static const char *letters[] = {"01110/10001/10001/11111/10001/10001/10001",
                                  "11110/10001/10001/11110/10001/10001/11110",
                                  "01111/10000/10000/10000/10000/10000/01111",
                                  "11110/10001/10001/10001/10001/10001/11110",
                                  "11111/10000/10000/11110/10000/10000/11111",
                                  "11111/10000/10000/11110/10000/10000/10000",
                                  "01111/10000/10000/10111/10001/10001/01110",
                                  "10001/10001/10001/11111/10001/10001/10001",
                                  "11111/00100/00100/00100/00100/00100/11111",
                                  "00111/00010/00010/00010/10010/10010/01100",
                                  "10001/10010/10100/11000/10100/10010/10001",
                                  "10000/10000/10000/10000/10000/10000/11111",
                                  "10001/11011/10101/10101/10001/10001/10001",
                                  "10001/11001/11001/10101/10011/10011/10001",
                                  "01110/10001/10001/10001/10001/10001/01110",
                                  "11110/10001/10001/11110/10000/10000/10000",
                                  "01110/10001/10001/10001/10101/10010/01101",
                                  "11110/10001/10001/11110/10100/10010/10001",
                                  "01111/10000/10000/01110/00001/00001/11110",
                                  "11111/00100/00100/00100/00100/00100/00100",
                                  "10001/10001/10001/10001/10001/10001/01110",
                                  "10001/10001/10001/10001/10001/01010/00100",
                                  "10001/10001/10001/10101/10101/11011/10001",
                                  "10001/10001/01010/00100/01010/10001/10001",
                                  "10001/10001/01010/00100/00100/00100/00100",
                                  "11111/00001/00010/00100/01000/10000/11111",
                                  "01110/10001/10011/10101/11001/10001/01110",
                                  "00100/01100/00100/00100/00100/00100/01110",
                                  "01110/10001/00001/00010/00100/01000/11111",
                                  "11110/00001/00001/01110/00001/00001/11110",
                                  "00010/00110/01010/10010/11111/00010/00010",
                                  "11111/10000/10000/11110/00001/00001/11110",
                                  "01111/10000/10000/11110/10001/10001/01110",
                                  "11111/00001/00010/00100/01000/01000/01000",
                                  "01110/10001/10001/01110/10001/10001/01110",
                                  "01110/10001/10001/01111/00001/00001/11110"};
  glEnable(GL_SCISSOR_TEST);
  glClearColor(red, green, blue, 1);
  int origin = x;
  for (unsigned char raw : text) {
    char c = std::toupper(raw);
    if (c == '\n') {
      x = origin;
      y += 18;
      continue;
    }
    const char *bits = c >= 'A' && c <= 'Z'   ? letters[c - 'A']
                       : c >= '0' && c <= '9' ? letters[26 + c - '0']
                                              : nullptr;
    if (c == '/')
      bits = "00001/00001/00010/00100/01000/10000/10000";
    if (c == '-')
      bits = "00000/00000/00000/11111/00000/00000/00000";
    if (c == ':')
      bits = "00000/00100/00100/00000/00100/00100/00000";
    if (c == '>')
      bits = "10000/01000/00100/00010/00100/01000/10000";
    if (c == '*')
      bits = "00000/10101/01110/11111/01110/10101/00000";
    if (bits) {
      for (int r = 0; r < 7; r++)
        for (int col = 0; col < 5; col++)
          if (bits[r * 6 + col] == '1') {
            glScissor(x + col * 2, height - y - r * 2 - 2, 2, 2);
            glClear(GL_COLOR_BUFFER_BIT);
          }
    } else if (c != ' ') {
      glScissor(x + 4, height - y - 8, 2, 2);
      glClear(GL_COLOR_BUFFER_BIT);
    }
    x += 12;
  }
  glDisable(GL_SCISSOR_TEST);
}
